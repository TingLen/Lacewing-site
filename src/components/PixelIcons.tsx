/**
 * 统一像素风格图标组件（16×16 几何像素矩阵）
 */
export function PixelIcon({
  name,
  size = 16,
  className = '',
}: {
  name: PixelIconName;
  size?: number;
  className?: string;
}) {
  const rects = ICON_RECTS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      fill="currentColor"
      className={`px-pixel-svg shrink-0 inline-block ${className}`.trim()}
      aria-hidden="true"
    >
      {rects.map(([x, y, w, h], idx) => (
        <rect key={idx} x={x} y={y} width={w} height={h} />
      ))}
    </svg>
  );
}
